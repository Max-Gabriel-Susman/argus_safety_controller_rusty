//! The Argus wire contract, in Rust.
//!
//! What every datagram between the board and the host has to agree on: the
//! checksum, and the packet layouts from `argus_wire.h`. The checks that
//! validate a packet before anything reads it come next.
//!
//! The crate is `no_std`: it uses `core` only, with no allocator and no
//! operating system underneath, so the same code runs in host tests and on
//! the Cortex-A9.
//!
//! It also forbids `unsafe` code. The one job here that needs it, turning
//! bytes into structs, belongs to zerocopy, whose derives check at compile
//! time that each struct is safe to convert.
#![no_std]
#![forbid(unsafe_code)]
pub mod crc;

/// The structs and constants of `argus_wire.h`, generated by bindgen.
///
/// Never edited by hand: `bash rust/tools/gen-wire.sh` rewrites it from the
/// header, and `--check` fails when the two disagree. The names are the C
/// ones, so they read the same on both sides of the FFI boundary.
#[allow(non_camel_case_types, reason = "the names match argus_wire.h")]
#[allow(
    clippy::indexing_slicing,
    reason = "bindgen's layout checks index inside const items: a bad index fails the build"
)]
pub mod generated;
